                "# 7. Train Model v6.0 with Focal Loss and Cosine Scheduler\n",
                "from tqdm.auto import tqdm\n",
                "from sklearn.metrics import f1_score, classification_report\n",
                "\n",
                "BATCH_SIZE = 16\n",
                "GRAD_ACCUM_STEPS = 2\n",
                "EPOCHS = 16\n",
                "\n",
                "# Normalized inverse frequency class weights\n",
                "counts = train_df[\"dialect\"].value_counts()\n",
                "raw_weights = [1.0 / max(counts[ID2DIALECT[i]], 1) for i in range(len(DIALECT_MAP))]\n",
                "class_weights = torch.tensor(raw_weights, dtype=torch.float).to(DEVICE)\n",
                "class_weights = class_weights / class_weights.sum() * len(DIALECT_MAP)\n",
                "\n",
                "class FocalLoss(nn.Module):\n",
                "    def __init__(self, alpha=None, gamma=2.0, label_smoothing=0.05):\n",
                "        super().__init__()\n",
                "        self.alpha = alpha\n",
                "        self.gamma = gamma\n",
                "        self.label_smoothing = label_smoothing\n",
                "    def forward(self, logits, targets):\n",
                "        ce_loss = nn.functional.cross_entropy(logits, targets, weight=self.alpha, label_smoothing=self.label_smoothing, reduction='none')\n",
                "        pt = torch.exp(-ce_loss)\n",
                "        return (((1.0 - pt) ** self.gamma) * ce_loss).mean()\n",
                "\n",
                "criterion = FocalLoss(alpha=class_weights, gamma=2.0, label_smoothing=0.05)\n",
                "\n",
                "backbone_params = [p for n, p in model.wav2vec2.named_parameters() if p.requires_grad]\n",
                "head_params = [p for n, p in model.named_parameters() if p.requires_grad and not n.startswith(\"wav2vec2\")]\n",
                "\n",
                "optimizer = torch.optim.AdamW([\n",
                "    {\"params\": backbone_params, \"lr\": 1.5e-5},\n",
                "    {\"params\": head_params, \"lr\": 3.5e-4}\n",
                "], weight_decay=1e-2)\n",
                "\n",
                "total_steps = (len(train_loader) // GRAD_ACCUM_STEPS) * EPOCHS\n",
                "warmup_steps = (len(train_loader) // GRAD_ACCUM_STEPS) * 2\n",
                "\n",
                "def lr_lambda(step):\n",
                "    if step < warmup_steps:\n",
                "        return float(step) / float(max(1, warmup_steps))\n",
                "    progress = float(step - warmup_steps) / float(max(1, total_steps - warmup_steps))\n",
                "    return max(0.05, 0.5 * (1.0 + np.cos(np.pi * progress)))\n",
                "\n",
                "scheduler = torch.optim.lr_scheduler.LambdaLR(optimizer, lr_lambda)\n",
                "scaler = torch.amp.GradScaler('cuda', enabled=(DEVICE.type == \"cuda\"))\n",
                "\n",
                "best_val_f1 = 0.0\n",
                "best_val_acc = 0.0\n",
                "os.makedirs(\"checkpoints\", exist_ok=True)\n",
                "\n",
                "print(f\"\\n🚀 Training Model v6.0 Pro on {DEVICE} for {EPOCHS} epochs...\")\n",
                "for epoch in range(1, EPOCHS + 1):\n",
                "    model.train()\n",
                "    total_train_loss = 0.0\n",
                "    optimizer.zero_grad()\n",
                "\n",
                "    loop = tqdm(train_loader, desc=f\"Epoch {epoch:02d}/{EPOCHS:02d} [Train]\")\n",
                "    for step, batch in enumerate(loop):\n",
                "        inputs = batch[\"input_values\"].to(DEVICE)\n",
                "        masks = batch[\"attention_mask\"].to(DEVICE)\n",
                "        labels = batch[\"dialect_label\"].to(DEVICE)\n",
                "\n",
                "        with torch.amp.autocast('cuda', enabled=(DEVICE.type == \"cuda\")):\n",
                "            outputs = model(input_values=inputs, attention_mask=masks)\n",
                "            loss = criterion(outputs.logits, labels)\n",
                "            loss_scaled = loss / GRAD_ACCUM_STEPS\n",
                "\n",
                "        scaler.scale(loss_scaled).backward()\n",
                "        total_train_loss += loss.item()\n",
                "\n",
                "        if (step + 1) % GRAD_ACCUM_STEPS == 0 or (step + 1) == len(train_loader):\n",
                "            scaler.unscale_(optimizer)\n",
                "            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)\n",
                "            scaler.step(optimizer)\n",
                "            scaler.update()\n",
                "            optimizer.zero_grad()\n",
                "            scheduler.step()\n",
                "\n",
                "        loop.set_postfix({\"loss\": f\"{loss.item():.4f}\"})\n",
                "\n",
                "    avg_train = total_train_loss / len(train_loader)\n",
                "\n",
                "    # Validation Loop\n",
                "    model.eval()\n",
                "    total_val_loss = 0.0\n",
                "    all_preds = []\n",
                "    all_targets = []\n",
